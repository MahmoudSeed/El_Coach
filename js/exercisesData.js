// استرجاع تمرين بالمعرف
function getExerciseById(id) {
    return exercisesDatabase.find(e => e.id === id) || null;
}

// استرجاع البدائل لتمرين معين
function getAlternativeExercises(exerciseId) {
    const ex = getExerciseById(exerciseId);
    if (!ex || !ex.alternatives) return [];
    return ex.alternatives.map(altId => getExerciseById(altId)).filter(Boolean);
}

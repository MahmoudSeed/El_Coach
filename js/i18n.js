    t(key, vars = {}) {
        const lang = this.getLang();
        let str = (this.dict[lang] && this.dict[lang][key]) || this.dict.ar[key] || key;
        Object.keys(vars).forEach(k => {
            str = str.replace(new RegExp(`\\{${k}\\}`, "g"), vars[k] !== undefined && vars[k] !== null ? vars[k] : "");
        });
        return str;
    },

    translateMuscle(muscle) {
        if (!this.isEn()) return muscle;
        const map = {
            "صدر": "Chest",
            "ظهر": "Back",
            "أكتاف": "Shoulders",
            "أرجل": "Legs",
            "ذراعين": "Arms",
            "بطن وكور": "Abs & Core"
        };
        return map[muscle] || muscle;
    },

    translateMealCategory(cat) {
        if (!this.isEn()) return cat;
        const map = {
            "إفطار": "Breakfast",
            "غداء": "Lunch",
            "عشاء": "Dinner",
            "سناكس": "Snacks"
        };
        return map[cat] || cat;
    },

    applyStaticTranslations() {
        const lang = this.getLang();
        const dir = lang === "en" ? "ltr" : "rtl";
        document.documentElement.lang = lang;
        document.documentElement.dir = dir;

        document.querySelectorAll("[data-i18n]").forEach(el => {
            const key = el.getAttribute("data-i18n");
            if (key) el.innerText = this.t(key);
        });

        document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
            const key = el.getAttribute("data-i18n-placeholder");
            if (key) el.setAttribute("placeholder", this.t(key));
        });

        const langLbl = document.getElementById("langToggleLabel");
        if (langLbl) {
            langLbl.innerText = this.t("lang_btn_label");
        }
    }
